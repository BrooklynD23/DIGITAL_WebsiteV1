import type { CSSProperties } from 'react';
import { PARTS, type Layout } from '../../_content/shades-concept-x';
import type { Flat } from './iso-kit';
import type { Inset, Label, Piece, Pose, Scene } from './geometry';
import './figure.css';

/** Parts whose tag changes between the planned layout and Concept X, or that exist in only one. */
export const CHANGED: ReadonlySet<string> = new Set(
  PARTS.filter((p) => !p.planned || !p.potential || p.planned.tag !== p.potential.tag).map((p) => p.id),
);

const POSE_SELECTOR: Readonly<Record<Pose, string>> = {
  pa: "[data-layout='planned'][data-pose='assembled']",
  pe: "[data-layout='planned'][data-pose='exploded']",
  xa: "[data-layout='potential'][data-pose='assembled']",
  xe: "[data-layout='potential'][data-pose='exploded']",
};
const xy = ([x, y]: Flat) => `${x} ${y}`;

/** Every piece in painter's order; each carries its four pose translates as CSS variables. Markup is generated by geometry.ts. */
function Pieces({ pieces }: { readonly pieces: readonly Piece[] }) {
  return (
    <>
      {pieces.map((p) => (
        <g
          key={p.key}
          className={p.cls ? `cx-piece ${p.cls}` : 'cx-piece'}
          data-part={p.part}
          data-only={p.only}
          data-ti={p.ti ? '' : undefined}
          data-changed={CHANGED.has(p.part) ? '' : undefined}
          style={{ '--pa': p.at.pa, '--pe': p.at.pe, '--xa': p.at.xa, '--xe': p.at.xe } as CSSProperties}
          dangerouslySetInnerHTML={{ __html: p.svg }}
        />
      ))}
    </>
  );
}

/** Labels for the taken-apart poses: a name and tag on desktop, a numbered callout keyed to the chips on a phone. */
function Labels({ labels }: { readonly labels: readonly Label[] }) {
  return (
    <g className="cx-lbls" aria-hidden="true">
      {labels.map((l) => {
        const layout: Layout = l.pose[0] === 'p' ? 'planned' : 'potential';
        const tag = PARTS.find((p) => p.id === l.part)?.[layout]?.tag;
        const dx = l.side === 'left' ? -1 : 1;
        const anchor = l.side === 'left' ? 'end' : 'start';
        return (
          <g key={`${l.pose}-${l.part}`} className="cx-lbl" data-pose={l.pose} data-part={l.part}>
            <g className="cx-lbl-full">
              <path className="cx-lbl-lead" d={`M${xy(l.anchor)}L${l.at[0] - dx * 4} ${l.at[1]}`} />
              <text x={l.at[0]} y={l.at[1] - 1} textAnchor={anchor} className="cx-lbl-name">
                {l.text}
              </text>
              {tag ? (
                <text x={l.at[0]} y={l.at[1] + 10} textAnchor={anchor} className="cx-lbl-tag">
                  {tag}
                </text>
              ) : null}
            </g>
            <g className="cx-lbl-num">
              <path className="cx-lbl-lead" d={`M${xy(l.anchor)}L${xy(l.callout)}`} />
              <circle className="cx-lbl-badge" cx={l.callout[0]} cy={l.callout[1]} r={19} />
              <text x={l.callout[0]} y={l.callout[1] + 8} textAnchor="middle" className="cx-lbl-n">
                {l.n}
              </text>
            </g>
            <circle className="cx-lbl-dot" cx={l.anchor[0]} cy={l.anchor[1]} r={2} />
          </g>
        );
      })}
    </g>
  );
}

/** Detail A: the pod cut open at about four times the scale, so the light path reads when assembled. */
function InsetView({ inset }: { readonly inset: Inset }) {
  const [x0, y0, x1, y1] = inset.box;
  const m = inset.marker.xa;
  return (
    <g className="cx-inset" aria-hidden="true">
      <clipPath id="cx-inset-clip">
        <rect x={x0} y={y0} width={x1 - x0} height={y1 - y0} rx={12} />
      </clipPath>
      <path className="cx-inset-lead" d={`M${xy(m)}L${x1 - 30} ${y0}`} />
      <circle className="cx-inset-mark" cx={m[0]} cy={m[1]} r={9} />
      <text className="cx-inset-letter" x={m[0]} y={m[1] + 3.6} textAnchor="middle">
        A
      </text>
      <rect className="cx-inset-frame" x={x0} y={y0} width={x1 - x0} height={y1 - y0} rx={12} />
      <g clipPath="url(#cx-inset-clip)">
        {inset.pieces.map((p) => (
          <g key={p.key} className={p.cls ? `cx-ipiece ${p.cls}` : 'cx-ipiece'} data-only={p.only} dangerouslySetInnerHTML={{ __html: p.svg }} />
        ))}
        {(['planned', 'potential'] as const).map((layout) => {
          const pts = inset.light[layout];
          const end = pts[pts.length - 1];
          return (
            <g key={layout} className="cx-inset-light" data-for={layout}>
              <path className="cx-light-path" d={pts.map((p, i) => `${i ? 'L' : 'M'}${xy(p)}`).join('')} data-pts={pts.map(xy).join(';')} />
              {pts.map(([x, y], i) => (
                <circle key={i} className="cx-light-node" cx={x} cy={y} r={i === pts.length - 1 ? 3.6 : 2.8} />
              ))}
              <g className="cx-word" transform={`translate(${xy(end)})`}>
                <rect x={-17} y={-21} width={34} height={14} rx={3} />
                <text x={0} y={-10.5} textAnchor="middle">
                  read
                </text>
              </g>
            </g>
          );
        })}
      </g>
      <text className="cx-inset-letter cx-inset-corner" x={x0 + 16} y={y0 + 22}>
        A
      </text>
    </g>
  );
}

/** The anatomy figure's static art: camera rules, pieces, the inset and the labels. Rendered inside Anatomy's svg. */
export function Art({ scene }: { readonly scene: Scene }) {
  const cams = scene.cams;
  const rules = cams ? (Object.keys(POSE_SELECTOR) as Pose[]).map((p) => `.cx-fig${POSE_SELECTOR[p]} .cx-cam{transform:${cams[p]}}`).join('') : '';
  return (
    <>
      {rules ? <style>{rules}</style> : null}
      <g className="cx-cam cx-art">
        <Pieces pieces={scene.pieces} />
      </g>
      {scene.inset ? <InsetView inset={scene.inset} /> : null}
      {scene.labels ? <Labels labels={scene.labels} /> : null}
    </>
  );
}

/** Static Concept X render for the hero: assembled, potential layout, no interaction. */
export function HeroArt({ scene, title }: { readonly scene: Scene; readonly title: string }) {
  return (
    <div className="iso cx-fig cx-hero" data-layout="potential" data-pose="assembled">
      <svg className="iso-svg" viewBox={`0 0 ${scene.width} ${scene.height}`} role="img" aria-label={title}>
        <g className="cx-art">
          <Pieces pieces={scene.pieces} />
        </g>
      </svg>
    </div>
  );
}
